import type {
  RestaurantMenu,
  LocalizedText,
  MenuItem,
} from "@/lib/restaurant/types";
const text = (uz: string, ru: string): LocalizedText => ({ uz, ru });
function item(
  restaurantId: string,
  categoryId: string,
  id: string,
  name: LocalizedText,
  description: LocalizedText,
  price: number,
  overrides: Partial<MenuItem> = {},
): MenuItem {
  return {
    restaurantId,
    categoryId,
    id,
    name,
    description,
    price,
    isAvailable: true,
    isVisible: true,
    isArchived: false,
    sortOrder: 0,
    ...overrides,
  };
}
